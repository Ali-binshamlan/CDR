-- هجرة: pending_resume_since — تتبّع صحيح لعداد استئناف الـ10 دقائق
--
-- خلل مكتشَف: عداد منع الاستئناف الفوري (RESUME_STABILITY_MINUTES) كان
-- يقرأ stopped_since ("منذ متى بدأ الإيقاف") بدل "منذ متى أصبحت القراءة
-- جيدة فعلياً". لو استمر الإيقاف 16 دقيقة (بقراءات سيئة متفرقة) قبل أن
-- تتحسّن القراءة أخيراً، كان النظام يعتبر عداد الـ10 دقائق منقضياً بالفعل
-- منذ بداية الإيقاف نفسه، فيسمح باستئناف فوري رغم عدم تراكم أي دقيقة
-- فعلية من القراءة الجيدة بعد — تناقض مباشر مع الغرض من هذا القيد.
--
-- pending_resume_since يُسجَّل أول مرة يكون فيها القرار الخام (لو تُرك
-- بلا قيد) أفضل من STOP_AFFECTED_ACTIVITY بينما القرار المخزَّن لا يزال
-- موقِفاً (resumeHoldApplied=true من evaluateDustCompliance) — ويُصفَّر
-- (null) بمجرد أن يتحول القرار المخزَّن فعلياً لغير موقِف (الاستئناف تم)،
-- أو يعود موقِفاً بحدّة كاملة مجدداً (القراءة ساءت من جديد).
-- =====================================================================

alter table public.current_dust_compliance_decisions
  add column if not exists pending_resume_since timestamptz;
