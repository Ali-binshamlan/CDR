import { describe, it, expect } from 'vitest';
import { pm10Risk } from './tables';

// =====================================================================
// طلب مستخدم صريح: "تغير الجدول تحت 250 نحن في أمان" — الفئات الثلاث
// السابقة (<100/<150/<250 بدرجات 10/25/45) دُمجت في فئة واحدة (<250،
// درجة 10 موحَّدة) — كل قراءة تحت حد التحذير التنظيمي (250، راجع
// PM10_WARNING_UG_M3 في dust-compliance-engine/rulebook.ts) تُعامَل بنفس
// درجة الخطر الدنيا. الفئتان الأعلى (<500 → 70، ≥500 → 90) بلا تغيير.
// =====================================================================

describe('pm10Risk — دمج الفئات تحت 250 (طلب مستخدم صريح)', () => {
  it.each([
    [0, 10],
    [50, 10],
    [99, 10],
    [100, 10],
    [120, 10],
    [149, 10],
    [150, 10],
    [200, 10],
    [249, 10],
  ])('pm10=%i → درجة 10 موحَّدة (قبل 250)', (pm10, expected) => {
    expect(pm10Risk(pm10)).toBe(expected);
  });

  it('pm10=250 (حد التحذير بالضبط) → القفزة إلى 70', () => {
    expect(pm10Risk(250)).toBe(70);
  });

  it('pm10=499 → لا تزال 70 (قبل حد 500)', () => {
    expect(pm10Risk(499)).toBe(70);
  });

  it('pm10=500 → 90 (أعلى درجة)', () => {
    expect(pm10Risk(500)).toBe(90);
  });

  it('pm10=1000 → تبقى 90 (لا فئة أعلى)', () => {
    expect(pm10Risk(1000)).toBe(90);
  });
});
