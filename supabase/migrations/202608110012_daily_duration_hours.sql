-- خطأ مكتشَف (المستخدم سأل: "لو مشروع مستمر 3 أيام والدوام 8 ساعات، هل
-- يُحتسب من وقت العمل فقط؟"): duration_hours المخزَّن حالياً = ساعات
-- الدوام اليومي × عدد أيام العمل الفعلية ضمن [startDate, endDate]
-- (app/components/AddActivityModal/index.tsx computeDurationHours) — أي
-- نشاط 8ص-4م لثلاثة أيام يُخزَّن duration_hours=24. كل مكان يحسب النافذة
-- الزمنية للنشاط (windowEnd = planned_date+planned_time + duration_hours)
-- كان يعامل هذه الـ24 ساعة كفترة واحدة متصلة بلا انقطاع ليلي — يعتبر
-- النشاط "جارياً" طوال الليل بين يوم 1 الساعة 4م ويوم 2 الساعة 8ص، رغم
-- عدم وجود دوام فعلي خلالها.
--
-- الإصلاح: عمود جديد daily_duration_hours يحفظ عدد ساعات الدوام اليومي
-- وحده (بمعزل عن duration_hours الإجمالية، التي تبقى كما هي لأغراض
-- إحصائية/عرض لا علاقة لها بالنافذة الزمنية). قابل لـNULL — صف قديم بلا
-- هذا العمود (أو نشاط بيوم واحد فقط حيث daily_duration_hours=duration_hours
-- عملياً) يُعامَل بفشل آمن في التطبيق: NULL يعني "استخدم duration_hours
-- كاملة كنافذة متصلة" (السلوك القديم بلا تغيير)، وهذا مطابق تماماً لكل
-- الأنشطة الحالية في الإنتاج (كلها يوم واحد فعلياً وقت هذا الإصلاح).
-- =====================================================================

alter table public.project_dust_profiles
  add column if not exists daily_duration_hours numeric;

comment on column public.project_dust_profiles.daily_duration_hours is
  'ساعات الدوام اليومي وحدها (بمعزل عن duration_hours الإجمالية عبر كل أيام النشاط) — تُستخدم لحساب النافذة الزمنية اليومية المتكررة (planned_time إلى planned_time+daily_duration_hours لكل يوم عمل ضمن مدى النشاط)، لا فترة متصلة واحدة. NULL = صف قديم أو نشاط بيوم واحد؛ يُعامَل كأن duration_hours كاملة هي النافذة اليومية (سلوك متطابق تماماً لنشاط يوم واحد).';
