-- =====================================================================
-- إصلاح جذري إضافي: lock_timeout على مستوى الدور authenticator نفسه
-- =====================================================================
-- 202608081001 (ALTER FUNCTION ... SET lock_timeout) لم يكفِ وحده — لوحظ
-- تعليق مستمر فوق 8 ثوانٍ رغم تطبيقه على كل الدوال المعنية. السبب المرجَّح:
-- PostgREST (المُنفَّذ عبره كل استدعاء من route.ts، دور authenticator) يمر
-- عبر connection pooler بوضع transaction-mode — إعدادات SET على مستوى
-- الدالة (function-level GUC) قد لا تُطبَّق بثبات عبر هذا الوضع، لأن
-- الجلسة الفعلية التي ينفَّذ عليها SET قد تُعاد تدويرها/استبدالها بين
-- استدعاءات الـpool بشكل لا يحترم دائماً نطاق الدالة وحدها.
--
-- ALTER ROLE ... SET lock_timeout يضبط الإعداد على مستوى الجلسة نفسها لكل
-- اتصال يُصادَق عبر دور authenticator (كل طلب PostgREST بلا استثناء)، بصرف
-- النظر عن نوع الـpooler أو نطاق الدالة المُستدعاة — طبقة حماية أعمّ وأضمن
-- من إعداد الدالة وحدها. 8 ثوانٍ (نفس القيمة، أقل من مهلة cron-job.org
-- 30 ثانية بهامش كافٍ).
alter role authenticator set lock_timeout = '8s';

-- statement_timeout عام أيضاً كطبقة حماية ثانية مستقلة عن lock_timeout —
-- يحد أي استعلام واحد (بما فيه استعلامات لا تنتظر قفلاً إطلاقاً، لكن قد
-- تتعطل لسبب آخر: شبكة، عدم استجابة الخادم) بمهلة قصوى صريحة بدل الاعتماد
-- فقط على مهلة Vercel/cron-job.org الخارجية.
alter role authenticator set statement_timeout = '15s';
