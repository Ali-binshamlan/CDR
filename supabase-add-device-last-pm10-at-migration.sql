-- =====================================================================
-- هجرة: عمود last_pm10_at منفصل لجهاز الرصد (project_devices)
--
-- المشكلة المكتشفة: last_reading_at عمود واحد مشترك لكل حقول القراءة
-- (رياح/PM10/رؤية/رطوبة/حرارة)، ويُحدَّث بلا شرط عند أي push جزئي من
-- الجهاز (راجع app/api/devices/ingest/route.ts) — حتى لو الحمولة تحمل
-- الحرارة فقط. فتظهر قراءة PM10 قديمة فعلياً وكأنها حديثة لمجرد أن الجهاز
-- أرسل حقلاً آخر مؤخراً، فيختفي تحذير قِدم القراءة (buildStalenessAdvisory
-- في Compliancewidgetcard.tsx) زوراً عن مستخدم يعتمد عليه لمعرفة موثوقية
-- بيانات PM10 المعروضة تحديداً.
--
-- الإصلاح: عمود last_pm10_at مستقل، يُحدَّث فقط عند وجود pm10 فعلياً في
-- حمولة push، ليعكس حداثة PM10 تحديداً بمعزل عن بقية الحقول. last_reading_at
-- يبقى كما هو (أعم "آخر اتصال من الجهاز على الإطلاق")، لا كسر توافقي على
-- أي استهلاك حالي له.
-- =====================================================================

alter table public.project_devices
  add column if not exists last_pm10_at timestamptz;

-- تعبئة أولية معقولة للصفوف الموجودة: قِدم PM10 لا يمكن معرفته بأثر رجعي
-- بدقة، فنستخدم last_reading_at كأفضل تقدير متاح (فشل آمن نحو "قد تكون
-- قديمة" بدل افتراض حداثة زائفة).
update public.project_devices
  set last_pm10_at = last_reading_at
  where last_pm10 is not null and last_pm10_at is null;
